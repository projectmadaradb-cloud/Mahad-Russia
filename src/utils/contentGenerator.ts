export function generatePageContent(
  context: PageContentContext,
  siteUrl: string
): GeneratedContent {
  const tradeData = matrixData.trades.find((t) => t.slug === context.trade);
  const cityData = matrixData.cities.find((c) => c.slug === context.city);

  if (!tradeData || !cityData) {
    throw new Error(`Invalid trade or city: ${context.trade}/${context.city}`);
  }

  // Generate meta title
  const title = `${tradeData.descriptionRu} ${cityData.nameRu} | Mahad Employment Services`;

  // Generate meta description
  const metaDescription = `Срочный наем ${tradeData.nameRu.toLowerCase()} ${cityData.nameRu}. Верифицированные специалисты, вывод 21–45 дней. EOR-аутстаффинг, полный комплайнс.`;

  // Generate H1
  const h1 = `Наем ${tradeData.nameRu} ${cityData.nameRu} из Индии`;

  // Build body content — mix regional + trade + legal + timeline + quality
  const bodyParagraphs: string[] = [];

  // Intro paragraph
  bodyParagraphs.push(
    `${tradeData.intentPrefix} ${cityData.nameRu} входит в число наших ключевых специализаций. Махад Мэнпауэр поставляет верифицированных ${tradeData.nameRu.toLowerCase()} для EPC-контрактов, логистических сетей и государственных объектов ${cityData.regionFull}.`
  );

  // Regional context
  const regionParagraphs = regionalParagraphs[context.city] || [];
  bodyParagraphs.push(regionParagraphs[0]);

  // Trade-specific details
  const tradeParagraphsForTrade = tradeParagraphs[context.trade] || [];
  bodyParagraphs.push(...tradeParagraphsForTrade.slice(0, 2));

  // More regional context
  if (regionParagraphs.length > 1) {
    bodyParagraphs.push(regionParagraphs[1]);
  }

  // Certification requirements
  const certParagraphs =
    context.category === "stroitelstvo"
      ? certificationParagraphs.stroitelstvo
      : certificationParagraphs.logistika;
  bodyParagraphs.push(certParagraphs[0]);

  // Additional trade specifics
  if (tradeParagraphsForTrade.length > 2) {
    bodyParagraphs.push(...tradeParagraphsForTrade.slice(2));
  }

  // Legal and compliance
  bodyParagraphs.push(legalParagraphs[0]);
  bodyParagraphs.push(legalParagraphs[1]);

  // Regional context conclusion
  if (regionParagraphs.length > 2) {
    bodyParagraphs.push(regionParagraphs[2]);
  }

  // Timeline
  bodyParagraphs.push(timelineParagraphs[0]);
  bodyParagraphs.push(timelineParagraphs[2]);

  // More compliance
  bodyParagraphs.push(legalParagraphs[2]);
  bodyParagraphs.push(legalParagraphs[3]);

  // Quality assurance
  bodyParagraphs.push(qualityParagraphs[0]);
  bodyParagraphs.push(qualityParagraphs[1]);

  // Final regional + quality
  if (regionParagraphs.length > 3) {
    bodyParagraphs.push(regionParagraphs[3]);
  }
  bodyParagraphs.push(qualityParagraphs[2]);

  // Generate LocalBusiness JSON-LD schema
  const jsonLd = {
    "@context": "https://schema.org",
    "@type": "LocalBusiness",
    name: `Mahad Employment Services: ${tradeData.nameRu} ${cityData.nameRu}`,
    description: metaDescription,
    image: `${siteUrl}/logo.avif`,
    url: `${siteUrl}/uslugi/${context.category}/${context.trade}/${context.city}`,
    address: {
      "@type": "PostalAddress",
      addressLocality: cityData.fullNameRu,
      addressRegion: cityData.region,
      addressCountry: "RU"
    },
    areaServed: cityData.regionFull,
    priceRange: "₽₽₽",
    openingHoursSpecification: {
      "@type": "OpeningHoursSpecification",
      dayOfWeek: ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday"],
      opens: "09:00",
      closes: "18:00"
    },
    contactPoint: {
      "@type": "ContactPoint",
      contactType: "продажи",
      telephone: "+7 (921) 982-4357",
      availableLanguage: ["ru", "en"]
    },
    aggregateRating: {
      "@type": "AggregateRating",
      ratingValue: "4.8",
      ratingCount: "156"
    },
    sameAs: [
      "https://wa.me/919219824357",
      "https://t.me/Mahadmanpowers",
      "https://mahadmanpowers.co.in"
    ],
    knowsAbout: [
      `Наем ${tradeData.nameRu}`,
      `Визовая поддержка ${cityData.nameRu}`,
      `EOR-аутстаффинг ${cityData.regionFull}`,
      "Трудовая мобилизация из Индии",
      "B2B кадровое решение"
    ]
  };

  return {
    title,
    metaDescription,
    h1,
    body: bodyParagraphs,
    jsonLd
  };
}
